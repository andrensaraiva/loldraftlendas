import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..', '..');
const manifest = JSON.parse(
  await readFile(resolve(root, 'src/data/draft-region-groups.json'), 'utf8'),
);
const target = resolve(root, 'supabase/migrations/20260929111000_online_duel_catalog.sql');
const roles = ['TOP', 'JUNGLE', 'MID', 'ADC', 'SUPPORT'];
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const rows = [];
const pools = new Map();

for (const entry of manifest.groups) {
  const players = JSON.parse(
    await readFile(resolve(root, `src/data/years/${entry.year}.json`), 'utf8'),
  );
  for (const group of entry.groups) {
    for (const player of players) {
      if (player.worldsYear !== entry.year) throw new Error(`Wrong year for ${player.id}`);
      const canonicalRegion = player.canonicalRegion ?? player.historicalLeague ?? player.region;
      if (!group.canonicalRegions.includes(canonicalRegion)) continue;
      if (!roles.includes(player.role)) throw new Error(`Unexpected role: ${player.role}`);
      rows.push([
        manifest.datasetVersion,
        player.id,
        player.role,
        entry.year,
        group.id,
        player.team,
      ]);
      const key = `${entry.year}/${group.id}/${player.role}`;
      pools.set(key, (pools.get(key) ?? 0) + 1);
    }
  }
}

for (const role of roles) {
  if (![...pools].some(([key, count]) => key.endsWith(`/${role}`) && count >= 3)) {
    throw new Error(`No eligible online duel pool for ${role}`);
  }
}

rows.sort((left, right) => {
  const leftKey = `${left[3]}/${left[4]}/${left[2]}/${left[1]}`;
  const rightKey = `${right[3]}/${right[4]}/${right[2]}/${right[1]}`;
  return leftKey < rightKey ? -1 : leftKey > rightKey ? 1 : 0;
});
if (new Set(rows.map((row) => `${row[0]}/${row[1]}/${row[4]}`)).size !== rows.length) {
  throw new Error('Duplicate online duel candidate');
}

const sql = [
  '-- Generated by npm run data:duel:build from the versioned player catalog.',
  'update public.duel_catalog_versions set active = false where active;',
  `insert into public.duel_catalog_versions (dataset_version, active) values (${quote(manifest.datasetVersion)}, true)`,
  'on conflict (dataset_version) do update set active = excluded.active;',
  'insert into public.duel_candidates (dataset_version, player_id, role, worlds_year, region_group, team) values',
  rows
    .map(
      (row) =>
        `  (${row.map((value) => (typeof value === 'number' ? value : quote(value))).join(', ')})`,
    )
    .join(',\n') + ';',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8');
  if (current !== sql) throw new Error('Online duel catalog migration is out of date');
  console.log(
    `Online duel catalog matches ${rows.length} entries from ${manifest.datasetVersion}.`,
  );
} else {
  await writeFile(target, sql, 'utf8');
  console.log(`Wrote ${rows.length} online duel candidates for ${manifest.datasetVersion}.`);
}
